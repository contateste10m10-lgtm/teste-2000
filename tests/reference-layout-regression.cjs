#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const js=fs.readFileSync(path.join(root,'blazarlab.js'),'utf8');
const changelog=fs.readFileSync(path.join(root,'CHANGELOG.md'),'utf8');
const version=fs.readFileSync(path.join(root,'VERSION'),'utf8').trim();
assert.equal(version,'1.3.29');
assert.match(html,/Flood, M\. W\.; Grimm, B\. \(2021\)/,'EntropyHub deve ter autores corretos');
assert.doesNotMatch(html,/Matthews, M\. J\.; Shaukat, A\.; Penney, G\./,'autoria bibliográfica incorreta não pode permanecer');
assert.match(html,/Bandt, C\.; Pompe, B\. \(2002\)/,'a referência de entropia de permutação deve estar listada');
assert.match(html,/href="https:\/\/doi\.org\/10\.1103\/PhysRevLett\.88\.174102"/,'o DOI de Bandt–Pompe deve estar correto');
assert.match(css,/\.visual-label-bottom\{bottom:56px/,'legenda inferior do hero deve ter faixa própria');
assert.match(css,/\.visual-index\{right:25px;bottom:20px/,'identificador do hero deve ficar numa segunda faixa');
assert.match(css,/@media\(max-width:480px\)\{[\s\S]*?\.hero-visual\{min-height:300px\}/,'hero deve reservar espaço suficiente em celular');
assert.match(js,/Bandas em keV · valores nas células = SampEn/,'a unidade energética deve aparecer uma vez fora das colunas');
assert.doesNotMatch(js,/ENERGY_BANDS\.map\(\(band, index\) => `<th scope="col" title="\$\{escapeXML\(band\.name\)\}"><span>\$\{escapeXML\(band\.short\)\}<\/span><small>keV<\/small><\/th>`\)/,'keV não deve se repetir em cada cabeçalho da matriz');
assert.match(css,/\.source-band-mobile-table thead th:not\(\.source-band-mobile-corner\)\{font-size:11px/,'cabeçalhos móveis devem ter texto maior');
assert.match(css,/\.footer-inner>a:last-child\{display:inline-flex;align-items:center;justify-self:start;min-height:44px/,'link de referências no rodapé deve ter alvo móvel de 44 px');
assert.equal((changelog.match(/^## 1\.3\.24\b/gm)||[]).length,1,'o changelog deve ter apenas um cabeçalho 1.3.24');
assert.equal((changelog.match(/^## 1\.3\.19\b/gm)||[]).length,1,'o changelog deve consolidar a versão 1.3.19');
assert.equal((changelog.match(/^## 1\.3\.22\b/gm)||[]).length,1,'o changelog deve manter apenas uma entrada 1.3.22 na sequência atual');
assert.match(html,/SINTÉTICO · 144 PONTOS\/BANDA/);
assert.match(html,/id="lightcurveRange">144 pontos/);
assert.match(js,/const MULTIBAND_N = 144;/);
console.log('OK: referências, hero, matriz móvel, alvo de toque no rodapé e histórico — BlazarLab 1.3.29.');
